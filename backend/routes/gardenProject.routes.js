const express = require('express')
const controller = require('../controllers/gardenProject.controller')
const { requireAuth, requireRole } = require('../middleware/auth.middleware')
const router = express.Router()
router.use(requireAuth, requireRole('client'))
router.get('/', controller.list)
router.post('/', controller.create)
router.get('/:projectId', controller.get)
router.patch('/:projectId', controller.update)
router.delete('/:projectId', controller.delete)
router.post('/:projectId/generate', controller.generate)
router.post('/:projectId/analyze', controller.analyze)
router.post('/:projectId/matches', controller.matches)
module.exports = router
